#!/usr/bin/env python3
"""Render authenticated PJSIP and WebRTC configuration for TomOS Home SIP."""
from __future__ import annotations
import argparse
import os
import re
import tempfile
from pathlib import Path

EXTENSION_RE = re.compile(r"^[1-9][0-9]{2,5}$")
SECRET_RE = re.compile(r"^[A-Za-z0-9._~-]{24,128}$")

def parse_extension(value: str) -> tuple[str, str]:
    if ":" not in value:
        raise argparse.ArgumentTypeError("extension must be NUMBER:SECRET")
    number, secret = value.split(":", 1)
    if not EXTENSION_RE.fullmatch(number):
        raise argparse.ArgumentTypeError(f"invalid extension number: {number!r}")
    if not SECRET_RE.fullmatch(secret):
        raise argparse.ArgumentTypeError("secret must be 24-128 safe ASCII characters")
    return number, secret

def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o640)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise

def render_pjsip(extensions: list[tuple[str, str]],
                 webrtc_extensions: list[tuple[str, str]] | None = None) -> str:
    lines = [
        "; Generated by TomOS Home SIP Server. Local-network use only.",
        "[global]", "type=global", "user_agent=TomOS-Home-SIP", "",
        "[transport-udp]", "type=transport", "protocol=udp", "bind=0.0.0.0:5060",
        "local_net=10.0.0.0/8", "local_net=172.16.0.0/12",
        "local_net=192.168.0.0/16", "",
        "; Browser clients use the Asterisk HTTPS server on TCP 8089.",
        "[transport-wss]", "type=transport", "protocol=wss", "bind=0.0.0.0", "",
    ]
    for number, secret in extensions:
        lines.extend([
            f"[{number}]", "type=endpoint", "transport=transport-udp",
            f"auth=auth-{number}", f"aors=aor-{number}", "context=tomos-internal",
            "disallow=all", "allow=alaw,ulaw", "direct_media=no",
            "rtp_symmetric=yes", "force_rport=yes", "rewrite_contact=yes",
            "timers=yes", "device_state_busy_at=1", "",
            f"[auth-{number}]", "type=auth", "auth_type=userpass",
            f"username={number}", f"password={secret}", "",
            f"[aor-{number}]", "type=aor", "max_contacts=3",
            "remove_existing=yes", "qualify_frequency=60", "",
        ])
    for number, secret in (webrtc_extensions or []):
        lines.extend([
            f"[webrtc-{number}]", "type=endpoint", "transport=transport-wss",
            f"auth=webrtc-auth-{number}", f"aors=webrtc-aor-{number}",
            "context=tomos-internal", f"callerid=TomOS Web Phone <{number}>",
            "identify_by=auth_username", "disallow=all", "allow=opus,alaw,ulaw", "webrtc=yes",
            "media_encryption=dtls", "dtls_auto_generate_cert=yes",
            "use_avpf=yes", "ice_support=yes", "rtcp_mux=yes",
            "media_use_received_transport=yes", "direct_media=no",
            "rtp_symmetric=yes", "force_rport=yes", "rewrite_contact=yes",
            "timers=yes", "",
            f"[webrtc-auth-{number}]", "type=auth", "auth_type=userpass",
            f"username={number}-web", f"password={secret}", "",
            f"[webrtc-aor-{number}]", "type=aor", "max_contacts=2",
            "remove_existing=yes", "qualify_frequency=60", "",
        ])
    return "\n".join(lines)

def render_dialplan(extensions: list[tuple[str, str]],
                    sccp_extensions: list[str] | None = None,
                    webrtc_extensions: list[str] | None = None,
                    country_code: str = "GB") -> str:
    if country_code not in {"GB", "INTL"}:
        raise ValueError("country_code must be GB or INTL")
    sip_numbers = {number for number, _ in extensions}
    sccp_numbers = set(sccp_extensions or [])
    browser_numbers = set(webrtc_extensions or [])
    numbers = sip_numbers | sccp_numbers
    lines = [
        "; Generated by TomOS Home SIP Server.",
        "[general]", "static=yes", "writeprotect=no", "", "[tomos-internal]",
        "exten => *65,1,Answer()", " same => n,Playback(demo-echotest)",
        " same => n,Echo()", " same => n,Hangup()",
    ]
    if country_code == "GB":
        lines.extend([
            "; UK national and international number recognition.",
            "; Outbound calls are deliberately blocked until a SIP trunk is configured.",
            "include => tomos-country-outbound",
        ])

    for number in sorted(numbers):
        targets = []
        if number in sip_numbers:
            targets.append(f"PJSIP/{number}")
        if number in sccp_numbers:
            targets.append(f"SCCP/{number}")
        if number in browser_numbers:
            targets.append(f"PJSIP/webrtc-{number}")
        technology = "&".join(targets)
        lines.extend([
            f"exten => {number},1,NoOp(TomOS internal call to {number})",
            f" same => n,Dial({technology},30)", " same => n,Hangup()",
        ])
    if country_code == "GB":
        lines.extend([
            "[tomos-country-outbound]",
            "exten => 999,1,NoOp(UK emergency call blocked: no emergency-capable trunk configured)",
            " same => n,Playback(all-circuits-busy-now)",
            " same => n,Hangup()",
            "exten => 112,1,NoOp(UK emergency call blocked: no emergency-capable trunk configured)",
            " same => n,Playback(all-circuits-busy-now)",
            " same => n,Hangup()",
            "exten => _0[1-9]X.,1,NoOp(UK national number normalisation)",
            " same => n,Set(TOMOS_E164=+44${EXTEN:1})",
            " same => n,NoOp(Normalised destination: ${TOMOS_E164})",
            " same => n,Playback(all-circuits-busy-now)",
            " same => n,Hangup()",
            "exten => _00X.,1,NoOp(International number normalisation)",
            " same => n,Set(TOMOS_E164=+${EXTEN:2})",
            " same => n,NoOp(Normalised destination: ${TOMOS_E164})",
            " same => n,Playback(all-circuits-busy-now)",
            " same => n,Hangup()",
            "",
        ])
    else:
        lines.append("; International/manual profile selected: no country-specific outbound patterns are enabled.")
    return "\n".join(lines)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--extension", action="append", type=parse_extension, required=True)
    parser.add_argument("--webrtc-extension", action="append", type=parse_extension, default=[])
    parser.add_argument("--country-code", choices=("GB", "INTL"), default="GB",
                        help="Country numbering profile (default: GB)")
    args = parser.parse_args()
    numbers = [number for number, _ in args.extension]
    browser_numbers = [number for number, _ in args.webrtc_extension]
    if len(numbers) != len(set(numbers)) or len(browser_numbers) != len(set(browser_numbers)):
        parser.error("duplicate extension numbers are not allowed")
    if not set(browser_numbers).issubset(set(numbers)):
        parser.error("every WebRTC identity must belong to an enabled SIP extension")
    atomic_write(args.output_dir / "pjsip.conf", render_pjsip(args.extension, args.webrtc_extension))
    atomic_write(args.output_dir / "extensions.conf", render_dialplan(
        args.extension, webrtc_extensions=browser_numbers, country_code=args.country_code
    ))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
