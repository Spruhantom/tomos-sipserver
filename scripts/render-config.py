#!/usr/bin/env python3
"""Render a minimal, authenticated PJSIP home PBX configuration."""
from __future__ import annotations
import argparse
import os
import re
import tempfile
from pathlib import Path

EXTENSION_RE = re.compile(r"^[1-9][0-9]{2,5}$")
SECRET_RE = re.compile(r"^[A-Za-z0-9._~-]{24,128}$")

def parse_extension(value: str) -> tuple[str, str]:
    if ":" not in value:
        raise argparse.ArgumentTypeError("extension must be NUMBER:SECRET")
    number, secret = value.split(":", 1)
    if not EXTENSION_RE.fullmatch(number):
        raise argparse.ArgumentTypeError(f"invalid extension number: {number!r}")
    if not SECRET_RE.fullmatch(secret):
        raise argparse.ArgumentTypeError("secret must be 24-128 safe ASCII characters")
    return number, secret

def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o640)
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise

def render_pjsip(extensions: list[tuple[str, str]]) -> str:
    lines = [
        "; Generated by TomOS Home SIP Server. Local-network use only.",
        "[global]", "type=global", "user_agent=TomOS-Home-SIP", "",
        "[transport-udp]", "type=transport", "protocol=udp", "bind=0.0.0.0:5060",
        "local_net=10.0.0.0/8", "local_net=172.16.0.0/12",
        "local_net=192.168.0.0/16", "",
    ]
    for number, secret in extensions:
        lines.extend([
            f"[{number}]", "type=endpoint", "transport=transport-udp",
            f"auth=auth-{number}", f"aors=aor-{number}", "context=tomos-internal",
            "disallow=all", "allow=alaw,ulaw", "direct_media=no",
            "rtp_symmetric=yes", "force_rport=yes", "rewrite_contact=yes",
            "timers=yes", "device_state_busy_at=1", "",
            f"[auth-{number}]", "type=auth", "auth_type=userpass",
            f"username={number}", f"password={secret}", "",
            f"[aor-{number}]", "type=aor", "max_contacts=3",
            "remove_existing=yes", "qualify_frequency=60", "",
        ])
    return "\n".join(lines)

def render_dialplan(extensions: list[tuple[str, str]]) -> str:
    numbers = {number for number, _ in extensions}
    lines = [
        "; Generated by TomOS Home SIP Server.", "[general]", "static=yes",
        "writeprotect=no", "", "[tomos-internal]",
        "exten => *65,1,Answer()", " same => n,Playback(demo-echotest)",
        " same => n,Echo()", " same => n,Hangup()",
    ]
    for number in sorted(numbers):
        lines.extend([
            f"exten => {number},1,NoOp(TomOS internal call to {number})",
            f" same => n,Dial(PJSIP/{number},30)", " same => n,Hangup()",
        ])
    lines.extend([
        "exten => _1XX,1,NoOp(TomOS three-digit internal extension)",
        " same => n,Dial(PJSIP/${EXTEN},30)", " same => n,Hangup()", "",
    ])
    return "\n".join(lines)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--extension", action="append", type=parse_extension, required=True)
    args = parser.parse_args()
    numbers = [number for number, _ in args.extension]
    if len(numbers) != len(set(numbers)):
        parser.error("duplicate extension numbers are not allowed")
    atomic_write(args.output_dir / "pjsip.conf", render_pjsip(args.extension))
    atomic_write(args.output_dir / "extensions.conf", render_dialplan(args.extension))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
