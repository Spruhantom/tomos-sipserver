"""Cisco SCCP handset validation and chan_sccp configuration rendering."""

from __future__ import annotations

import re

from .yealink import normalize_mac, validate_server_host

SUPPORTED_MODELS = frozenset({"7940", "7960", "7970"})
EXTENSION_PATTERN = re.compile(r"^[1-9][0-9]{2,5}$")
SAFE_CONFIG_TEXT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._()'-]{0,63}$")


def normalize_model(value: str) -> str:
    """Return a canonical Cisco model number from a narrowly allowlisted input."""
    if not isinstance(value, str):
        raise ValueError("Unsupported Cisco SCCP model")
    candidate = re.sub(r"^Cisco\s+", "", value.strip(), flags=re.IGNORECASE)
    candidate = candidate.upper().replace(" ", "")
    if candidate not in SUPPORTED_MODELS:
        raise ValueError("Unsupported Cisco model; supported inventory models are 7940, 7960 and 7970")
    return candidate


def render_sccp_devices(devices: list[dict]) -> str:
    """Render chan_sccp device and line sections for registered Cisco handsets.

    The generated file contains no SIP credentials. Device registration is
    identified by the handset MAC address and the configured SCCP driver.
    """
    normalized = []
    for device in devices:
        mac = normalize_mac(device["mac"])
        model = normalize_model(device["model"])
        extension = str(device["extension"])
        display_name = str(device["display_name"]).strip()
        if not EXTENSION_PATTERN.fullmatch(extension):
            raise ValueError("Invalid extension number")
        if not SAFE_CONFIG_TEXT.fullmatch(display_name):
            raise ValueError("Display name contains characters unsupported by SCCP configuration")
        normalized.append((mac, model, extension, display_name))

    lines = [
        "; Generated by TomOS SIP Server. Do not edit this file.",
        "; Device profiles are managed through the TomOS dashboard/API.",
        "",
    ]
    line_sections = {}
    for mac, model, extension, display_name in sorted(normalized):
        lines.extend([
            f"[SEP{mac}]",
            "type = device",
            f"devicetype = {model}",
            f"description = {display_name}",
            f"button = line, {extension}",
            "keepalive = 60",
            "transfer = on",
            "park = off",
            "cfwdall = on",
            "cfwdbusy = on",
            "cfwdnoanswer = on",
            "",
        ])
        line_sections.setdefault(extension, display_name)

    for extension, display_name in sorted(line_sections.items()):
        lines.extend([
            f"[{extension}]",
            "type = line",
            f"label = {display_name}",
            f"description = TomOS extension {extension}",
            f"cid_name = {display_name}",
            f"cid_num = {extension}",
            "context = tomos-internal",
            "incominglimit = 1",
            "transfer = on",
            "musicclass = default",
            "language = en",
            "",
        ])
    return "\n".join(lines)


__all__ = [
    "SUPPORTED_MODELS", "normalize_mac", "normalize_model",
    "render_sccp_devices", "validate_server_host",
]
