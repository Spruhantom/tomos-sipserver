"""Cisco SCCP model profiles and hardware compatibility metadata."""
from __future__ import annotations

import re
import xml.etree.ElementTree as ET

from .yealink import normalize_mac, validate_server_host

# Model families and profile structures from the pinned AI3I/chan_sccp templates.
# Firmware and physical handset operation still require device-level validation.
CHAN_SCCP_COMMIT = "9591e4583c0c3b682d30d253ce77d596f040acf8"
MODEL_PROFILES = {
    "7940": {
        "profile_family": "7940_7960",
        "template": "SEP0000000000.cnf.xml_7940_7960_template",
        "driver_model": "7940",
    },
    "7960": {
        "profile_family": "7940_7960",
        "template": "SEP0000000000.cnf.xml_7940_7960_template",
        "driver_model": "7960",
    },
    "7970": {
        "profile_family": "797x",
        "template": "SEP0000000000.cnf.xml_797x_template",
        "driver_model": "7970",
    },
}
SUPPORTED_MODELS = frozenset(MODEL_PROFILES)
EXTENSION_PATTERN = re.compile(r"^[1-9][0-9]{2,5}$")
DISPLAY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._()\-]{0,63}$")


def normalize_model(value: str) -> str:
    if not isinstance(value, str):
        raise ValueError("Unsupported Cisco SCCP model")
    candidate = re.sub(r"^Cisco\s+", "", value.strip(), flags=re.IGNORECASE)
    candidate = candidate.upper().replace(" ", "")
    if candidate not in SUPPORTED_MODELS:
        raise ValueError("Unsupported Cisco model; supported models are 7940, 7960 and 7970")
    return candidate


def model_compatibility(value: str) -> dict:
    """Describe software/profile support without implying firmware or hardware testing."""
    model = normalize_model(value)
    profile = MODEL_PROFILES[model]
    return {
        "model": model,
        "driver_model": profile["driver_model"],
        "profile_family": profile["profile_family"],
        "profile_template": profile["template"],
        "profile_generation": "model_specific",
        "template_source_commit": CHAN_SCCP_COMMIT,
        "firmware_validation": "manual_required",
        "hardware_test_status": "not_tested",
        "compatibility_status": "driver_and_profile_supported_hardware_unverified",
    }


def render_sccp_config(
    *, mac: str, model: str, extension: str, display_name: str,
    server_host: str, sip_password: str | None = None,
) -> str:
    """Render chan_sccp device and line sections; SIP password is not used by SCCP."""
    canonical_mac = normalize_mac(mac)
    canonical_model = normalize_model(model)
    validate_server_host(server_host)
    if not isinstance(extension, str) or not EXTENSION_PATTERN.fullmatch(extension):
        raise ValueError("Invalid extension number")
    if not isinstance(display_name, str) or not DISPLAY_PATTERN.fullmatch(display_name):
        raise ValueError("Display name must use letters, numbers, spaces, dots, underscores, parentheses or hyphens")
    return (
        "; Managed by TomOS SIP Server. Do not edit this file by hand.\n"
        f"[SEP{canonical_mac}]\n"
        "type = device\n"
        f"devicetype = {canonical_model}\n"
        f"description = {display_name}\n"
        f"button = line, {extension}\n\n"
        f"[{extension}]\n"
        "type = line\n"
        f"id = {extension}\n"
        f"label = {display_name}\n"
        f"description = {display_name}\n"
        "context = tomos-internal\n"
        f"cid_num = {extension}\n"
        f"cid_name = {display_name}\n\n"
    )


def _set_text(parent: ET.Element, tag: str, value: str) -> ET.Element:
    element = ET.SubElement(parent, tag)
    element.text = value
    return element


def _add_datetime(pool: ET.Element, host: str, *, legacy: bool) -> None:
    setting = ET.SubElement(pool, "dateTimeSetting")
    _set_text(setting, "name", "United_Kingdom")
    _set_text(setting, "dateTemplate", "D-M-YA" if legacy else "D/M/Y")
    _set_text(setting, "timeZone", "GMT Standard/Daylight Time")
    ntps = ET.SubElement(setting, "ntps")
    ntp = ET.SubElement(ntps, "ntp")
    _set_text(ntp, "name", host)
    _set_text(ntp, "ntpMode", "Unicast")


def _add_call_manager(pool: ET.Element, host: str, port: int, *, modern: bool) -> None:
    group = ET.SubElement(pool, "callManagerGroup")
    members = ET.SubElement(group, "members")
    member = ET.SubElement(members, "member", {"priority": "0"})
    manager = ET.SubElement(member, "callManager")
    if modern:
        _set_text(manager, "name", "TomOS")
    ports = ET.SubElement(manager, "ports")
    _set_text(ports, "ethernetPhonePort", str(port))
    _set_text(manager, "processNodeName", host)


def _add_srst(pool: ET.Element, *, modern: bool) -> None:
    srst = ET.SubElement(pool, "srstInfo")
    if not modern:
        _set_text(srst, "name", "Disable")
    _set_text(srst, "srstOption", "Disable")
    if not modern:
        _set_text(srst, "userModifiable", "false")
    for tag in ("ipAddr1", "port1", "ipAddr2", "port2"):
        ET.SubElement(srst, tag)
    if not modern:
        ET.SubElement(srst, "ipAddr3")
        ET.SubElement(srst, "port3")
    else:
        _set_text(srst, "isSecure", "false")


def _add_locale(device: ET.Element, *, modern: bool) -> None:
    locale = ET.SubElement(device, "userLocale")
    _set_text(locale, "name", "English_United_Kingdom")
    _set_text(locale, "uid", "1")
    _set_text(locale, "langCode", "en_GB")
    _set_text(locale, "version", "7.1.0.1(1)")
    _set_text(locale, "winCharSet", "iso-8859-1")
    _set_text(device, "networkLocale", "United_Kingdom")
    info = ET.SubElement(device, "networkLocaleInfo")
    _set_text(info, "name", "United_Kingdom")
    _set_text(info, "uid", "64")
    _set_text(info, "version", "7.1.0.1(1)")


def _render_7940_7960(host: str, port: int) -> ET.Element:
    device = ET.Element("device")
    pool = ET.SubElement(device, "devicePool")
    _add_datetime(pool, host, legacy=True)
    _add_call_manager(pool, host, port, modern=False)
    _add_srst(pool, modern=False)
    vendor = ET.SubElement(device, "vendorConfig")
    for tag, value in (
        ("disableSpeaker", "false"), ("disableSpeakerAndHeadset", "false"),
        ("forwardingDelay", "1"), ("pcPort", "0"), ("settingsAccess", "1"),
        ("garp", "0"), ("voiceVlanAccess", "0"), ("videoCapability", "0"),
        ("autoSelectLineEnable", "0"), ("autoCallSelect", "0"), ("webAccess", "0"),
        ("daysDisplayNotActive", "1,7"), ("displayOnTime", "08:30"),
        ("displayOnDuration", "11:30"), ("displayIdleTimeout", "01:00"),
        ("displayOnWhenIncomingCall", "1"),
    ):
        _set_text(vendor, tag, value)
    _add_locale(device, modern=False)
    _set_text(device, "deviceSecurityMode", "1")
    _set_text(device, "idleTimeout", "3600")
    for tag in ("authenticationURL", "idleURL", "informationURL", "messagesURL",
                "proxyServerURL", "servicesURL", "directoryURL"):
        ET.SubElement(device, tag)
    _set_text(device, "dscpForSCCPPhoneConfig", "104")
    _set_text(device, "dscpForSCCPPhoneServices", "0")
    _set_text(device, "dscpForCm2Dvce", "184")
    return device


