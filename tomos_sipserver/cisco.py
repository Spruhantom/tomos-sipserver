"""Cisco SCCP configuration and SEP XML profile rendering."""
from __future__ import annotations

import re
import xml.etree.ElementTree as ET

from .yealink import normalize_mac, validate_server_host

SUPPORTED_MODELS = frozenset({"7940", "7960", "7970"})
EXTENSION_PATTERN = re.compile(r"^[1-9][0-9]{2,5}$")
DISPLAY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._()\-]{0,63}$")


def normalize_model(value: str) -> str:
    if not isinstance(value, str):
        raise ValueError("Unsupported Cisco SCCP model")
    candidate = re.sub(r"^Cisco\s+", "", value.strip(), flags=re.IGNORECASE)
    candidate = candidate.upper().replace(" ", "")
    if candidate not in SUPPORTED_MODELS:
        raise ValueError("Unsupported Cisco model; supported models are 7940, 7960 and 7970")
    return candidate


def render_sccp_config(
    *, mac: str, model: str, extension: str, display_name: str,
    server_host: str, sip_password: str | None = None,
) -> str:
    """Render chan_sccp device and line sections; SIP password is not used by SCCP."""
    canonical_mac = normalize_mac(mac)
    canonical_model = normalize_model(model)
    validate_server_host(server_host)
    if not isinstance(extension, str) or not EXTENSION_PATTERN.fullmatch(extension):
        raise ValueError("Invalid extension number")
    if not isinstance(display_name, str) or not DISPLAY_PATTERN.fullmatch(display_name):
        raise ValueError("Display name must use letters, numbers, spaces, dots, underscores, parentheses or hyphens")
    device_section = f"SEP{canonical_mac}"
    return (
        f"; Managed by TomOS SIP Server. Do not edit this file by hand.\n"
        f"[{device_section}]\n"
        f"type = device\n"
        f"devicetype = {canonical_model}\n"
        f"description = {display_name}\n"
        f"button = line, {extension}\n"
        f"\n"
        f"[{extension}]\n"
        f"type = line\n"
        f"id = {extension}\n"
        f"label = {display_name}\n"
        f"description = {display_name}\n"
        f"context = tomos-internal\n"
        f"cid_num = {extension}\n"
        f"cid_name = {display_name}\n"
        f"\n"
    )


def render_phone_xml(*, mac: str, server_host: str, sccp_port: int = 2000) -> str:
    """Render a conservative SEP profile based on chan_sccp's 7940/7960 template."""
    canonical_mac = normalize_mac(mac)
    host = validate_server_host(server_host)
    if isinstance(sccp_port, bool) or not isinstance(sccp_port, int) or not 1 <= sccp_port <= 65535:
        raise ValueError("Invalid SCCP port")

    device = ET.Element("device")
    pool = ET.SubElement(device, "devicePool")
    date_time = ET.SubElement(pool, "dateTimeSetting")
    ET.SubElement(date_time, "name").text = "United Kingdom"
    ET.SubElement(date_time, "dateTemplate").text = "D/M/Y"
    ET.SubElement(date_time, "timeZone").text = "GMT Standard/Daylight Time"
    ntps = ET.SubElement(date_time, "ntps")
    ntp = ET.SubElement(ntps, "ntp")
    ET.SubElement(ntp, "name").text = host
    ET.SubElement(ntp, "ntpMode").text = "Unicast"
    group = ET.SubElement(pool, "callManagerGroup")
    members = ET.SubElement(group, "members")
    member = ET.SubElement(members, "member", {"priority": "0"})
    manager = ET.SubElement(member, "callManager")
    ports = ET.SubElement(manager, "ports")
    ET.SubElement(ports, "ethernetPhonePort").text = str(sccp_port)
    ET.SubElement(manager, "processNodeName").text = host
    srst = ET.SubElement(pool, "srstInfo")
    ET.SubElement(srst, "name").text = "Disable"
    ET.SubElement(srst, "srstOption").text = "Disable"
    ET.SubElement(srst, "userModifiable").text = "false"
    for tag in ("ipAddr1", "port1", "ipAddr2", "port2", "ipAddr3", "port3"):
        ET.SubElement(srst, tag)
    ET.SubElement(device, "loadInformation").text = ""
    ET.SubElement(device, "vendorConfig")
    locale = ET.SubElement(device, "userLocale")
    ET.SubElement(locale, "name").text = "English_United_Kingdom"
    ET.SubElement(locale, "uid").text = "1"
    ET.SubElement(locale, "langCode").text = "en_GB"
    ET.SubElement(locale, "version").text = "7.1.0.1(1)"
    ET.SubElement(locale, "winCharSet").text = "iso-8859-1"
    ET.SubElement(device, "networkLocale").text = "United_Kingdom"
    ET.SubElement(device, "deviceSecurityMode").text = "1"
    ET.SubElement(device, "idleTimeout").text = "3600"
    ET.SubElement(device, "authenticationURL")
    ET.SubElement(device, "idleURL")
    ET.SubElement(device, "informationURL")
    ET.SubElement(device, "messagesURL")
    ET.SubElement(device, "proxyServerURL")
    ET.SubElement(device, "servicesURL")
    ET.SubElement(device, "directoryURL")
    ET.SubElement(device, "dscpForSCCPPhoneConfig").text = "104"
    ET.SubElement(device, "dscpForSCCPPhoneServices").text = "0"
    ET.SubElement(device, "dscpForCm2Dvce").text = "184"
    ET.indent(device, space="  ")
    return ET.tostring(device, encoding="utf-8", xml_declaration=True).decode("utf-8") + "\n"


__all__ = ["SUPPORTED_MODELS", "normalize_mac", "normalize_model", "render_sccp_config", "render_phone_xml", "validate_server_host"]
